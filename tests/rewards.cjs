const fs=require('node:fs'),path=require('node:path');
module.exports=async function testRewards(page,url,screenshotDir='outputs'){
  const assert=(ok,message)=>{if(!ok)throw Error(message);};
  const cloud=async(predicate)=>page.waitForFunction(predicate);
  await page.locator('#goal-form [name=goal]').fill('10080');
  await page.locator('#goal-form button[type=submit], #goal-form button:not([type])').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.goal===10080));
  await page.locator('#reward-form [name=title]').fill('Takeaway');
  await page.locator('#reward-form [name=level]').fill('2');
  await page.locator('#reward-form button').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.rewards.some(x=>x.title==='Takeaway')));
  let card=page.locator('.personal-reward').filter({hasText:'Takeaway'});
  assert((await card.textContent()).includes('50 XP to go'),'Reward progress should use 100 XP levels');
  await card.locator('[data-edit-reward]').click();
  await page.locator('#reward-edit-form [name=title]').fill('Cancelled edit');
  await page.locator('#cancel-reward-edit').click();
  assert(await card.isVisible(),'Cancelling an edit changed the reward');
  await card.locator('[data-edit-reward]').click();
  await page.locator('#reward-edit-form [name=title]').fill('Takeaway & film');
  await page.locator('#reward-edit-form [name=level]').fill('3');
  await page.locator('#reward-edit-form button').filter({hasText:'Save changes'}).click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.rewards.some(x=>x.title==='Takeaway & film'&&x.level===3)));
  await page.reload();await page.waitForSelector('#content .hero');await page.goto(url+'#rewards');await page.waitForSelector('.personal-reward');
  assert((await page.locator('.personal-reward').textContent()).includes('Takeaway & film'),'Reward edit did not persist');
  // Cross exact overall and subject level boundaries through real study logging.
  for(const [minutes,total,overall,subject] of [[49,99,1,1],[1,100,2,1],[19,119,2,1],[1,120,2,2],[79,199,2,2],[1,200,3,2]]){
    await page.locator('#log').click();
    await page.locator('#session [name=target]').selectOption('Politics');
    await page.locator('#session [name=activity]').selectOption('Flashcards');
    await page.locator('#session [name=topic]').fill('Level boundary '+total);
    await page.locator('#session [name=minutes]').fill(String(minutes));
    await page.locator('#session button').filter({hasText:'Save session'}).click();
    await cloud(()=>document.getElementById('storage').textContent==='Saved to your account');
    const hero=await page.locator('#content>.hero').textContent();
    assert(hero.includes('Level '+overall+' · '+total+' XP'),'Wrong overall level at '+total+' XP');
    assert(hero.includes((100-total%100)+' XP to your next level'),'Wrong remaining XP at '+total);
    await page.goto(url+'#subjects/Politics');await page.waitForSelector('.exam-chart');
    assert((await page.locator('#content>.card').first().textContent()).includes('Level '+subject+' ·'),'Wrong subject level at '+total+' overall XP');
    await page.goto(url+'#rewards');await page.waitForSelector('#goal-form');
  }
  assert(await page.locator('.reward-available').count()===1,'Reward did not unlock at its new level');
  await page.locator('#reward-form [name=title]').fill('A film night');
  await page.locator('#reward-form [name=level]').fill('5');
  await page.locator('#reward-form button').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.rewards.length===2));
  await page.goto(url+'#dashboard');await page.waitForSelector('.dashboard-tools');
  assert((await page.locator('.card').filter({hasText:'Your overall level'}).textContent()).includes('Level 3'),'Dashboard level differs from rewards');
  await page.goto(url+'#rewards');await page.waitForSelector('#goal-form');
  fs.mkdirSync(screenshotDir,{recursive:true});
  await page.locator('.personal-rewards').screenshot({path:path.join(screenshotDir,'stride-rewards-light.png')});
  await page.locator('#theme-toggle').click();
  await page.locator('.personal-rewards').screenshot({path:path.join(screenshotDir,'stride-rewards-dark.png')});
  await page.locator('#theme-toggle').click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('.personal-rewards').scrollIntoViewIfNeeded();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'Rewards overflow on mobile');
  await page.locator('.personal-rewards').screenshot({path:path.join(screenshotDir,'stride-rewards-mobile.png')});
  await page.setViewportSize({width:1440,height:1000});
  card=page.locator('.personal-reward').filter({hasText:'Takeaway & film'});
  page.once('dialog',d=>d.dismiss());await card.locator('[data-delete-reward]').click();
  assert(await card.count()===1,'Cancelled deletion removed the reward');
  page.once('dialog',d=>d.accept());await card.locator('[data-delete-reward]').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.rewards.length===1&&r.state.rewards[0].title==='A film night'));
  await page.reload();await page.waitForSelector('#content .hero');await page.goto(url+'#rewards');await page.waitForSelector('.personal-reward');
  assert((await page.locator('.personal-reward').textContent()).includes('A film night'),'Deleting achieved reward removed another reward');
  assert((await page.locator('#content>.hero').textContent()).includes('200 XP'),'Deleting a reward changed XP');
  page.once('dialog',d=>d.accept());await page.locator('.personal-reward [data-delete-reward]').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.rewards.length===0));
  assert(await page.locator('.reward-empty').isVisible(),'No empty state after deleting last reward');
  page.once('dialog',d=>d.accept());await page.locator('#remove-goal').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.goal===null));
  await page.reload();await page.waitForSelector('#content .hero');await page.goto(url+'#rewards');await page.waitForSelector('#goal-form');
  assert(await page.locator('#remove-goal').count()===0,'Weekly goal removal did not persist');
  await page.locator('#goal-form [name=goal]').fill('180');await page.locator('#goal-form button').click();
  await cloud(()=>Object.values(JSON.parse(localStorage.getItem('test.rows'))).some(r=>r.state.goal===180));
  console.log('Passed: editable reward cards, cancelled edits/deletions, saved edits/deletions, 100 XP overall/subject boundaries, reward unlocking, weekly goal removal/restoration, light/dark/mobile layout.');
};
