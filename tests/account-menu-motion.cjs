const assert=require('node:assert/strict');
module.exports=async function checkAccountMenuMotion(page){
  const trigger=page.locator('#account-menu summary');
  const result=await page.evaluate(async()=>{
    const menu=document.getElementById('account-menu'),panel=menu.querySelector('.account-menu-panel'),trigger=menu.querySelector('summary');
    const frame=()=>new Promise(requestAnimationFrame);
    const click=()=>trigger.dispatchEvent(new MouseEvent('click',{bubbles:true,cancelable:true,detail:1}));
    const snapshot=()=>({opacity:Number(getComputedStyle(panel).opacity),transform:getComputedStyle(panel).transform,inert:panel.inert,open:menu.open});
    const durations={enter:getComputedStyle(menu).getPropertyValue('--menu-enter').trim(),exit:getComputedStyle(menu).getPropertyValue('--menu-exit').trim()};
    // Slow only the test fixture, so animation checkpoints are independent of CI speed.
    menu.style.setProperty('--menu-enter','1000ms');menu.style.setProperty('--menu-exit','800ms');
    click();await frame();
    const animations=panel.getAnimations().filter(a=>['opacity','transform'].includes(a.transitionProperty));
    animations.forEach(a=>{a.pause();a.currentTime=250;});await frame();
    const entering=snapshot(),origin=getComputedStyle(panel).transformOrigin;
    animations.forEach(a=>a.finish());await frame();
    const entered=snapshot();
    click();await frame();
    const exitAnimations=panel.getAnimations().filter(a=>['opacity','transform'].includes(a.transitionProperty));
    exitAnimations.forEach(a=>{a.pause();a.currentTime=100;});await frame();
    const leaving=snapshot();
    click();await frame();
    const reversed=snapshot();
    panel.getAnimations().forEach(a=>a.finish());await frame();
    const reopened=snapshot();
    menu.style.removeProperty('--menu-enter');menu.style.removeProperty('--menu-exit');
    return {durations,entering,entered,leaving,reversed,reopened,origin,animationCount:animations.length};
  });
  assert.deepEqual(result.durations,{enter:'180ms',exit:'150ms'});
  assert.equal(result.animationCount,2,'Opening must animate opacity and transform');
  assert(result.entering.opacity>0&&result.entering.opacity<1,'Opening jumps to final opacity');
  assert.notEqual(result.entering.transform,'none','Opening has no spatial transition');
  assert.equal(result.entered.opacity,1);assert.equal(result.entered.inert,false);
  assert(result.leaving.open&&result.leaving.inert,'Closing panel must stay rendered but stop accepting input: '+JSON.stringify(result));
  assert(result.leaving.opacity>0&&result.leaving.opacity<1,'Closing jumps out of view');
  assert(result.reversed.open&&!result.reversed.inert,'Reopening during exit fails');
  assert(result.reopened.open&&result.reopened.opacity===1,'Old closing timer hides reopened menu');
  assert.match(result.origin,/px 0px$/,'Menu must expand from its top edge');
  await page.keyboard.press('Escape');
  await trigger.press('Enter');
  assert.equal(await page.locator('#account-menu').getAttribute('data-instant'),'true','Keyboard opening animates');
  assert.equal(await page.locator('.account-menu-panel').evaluate(el=>Number(getComputedStyle(el).opacity)),1);
  await page.keyboard.press('Escape');await trigger.press('ArrowDown');
  assert(await page.locator('[data-account-edit=profile]').evaluate(el=>el===document.activeElement),'ArrowDown does not reach first action');
  await page.keyboard.press('Escape');await trigger.press('ArrowUp');
  assert(await page.locator('#signout').evaluate(el=>el===document.activeElement),'ArrowUp does not reach last action');
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('#account-menu').getAttribute('open'),null,'Tabbing outside does not close instantly');
  await page.emulateMedia({reducedMotion:'reduce'});
  await trigger.click();
  assert.equal(await page.locator('.account-menu-panel').evaluate(el=>getComputedStyle(el).transform),'none','Reduced motion still scales/slides');
  await page.locator('.account-menu-panel').evaluate(el=>Promise.all(el.getAnimations().map(a=>a.finished.catch(()=>{}))));
  await page.keyboard.press('Escape');await page.emulateMedia({reducedMotion:'no-preference'});
  await trigger.click();await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.account-menu-panel').evaluate(el=>getComputedStyle(el).transform),'none','Changing motion preference leaves a transform');
  await page.keyboard.press('Escape');await page.emulateMedia({reducedMotion:'no-preference'});
  console.log('Passed: account menu entrance/exit, interruptible reversal, keyboard instant response, focus navigation and reduced-motion changes.');
};
